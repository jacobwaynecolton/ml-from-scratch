import torch

# Fake logits
fake_logits = torch.tensor([
    [9,-4.4,3.1,9.2],
    [-2.3,1.1,4.3,4.0]])

# (B,V) logits being passed in
def top_k_filter(logits,k):

  # Use a clamp to deal with circumstances where k > len(v)
  k = min(k,logits.shape[-1])
  # Using pytorch's topk function to isolate the topk from the fake_logits list
  topk_values, topk_indices = torch.topk(logits,k)

  # Finding the kth value for each sample
  kth_value = topk_values[:,-1][:,None]
  # creating the mask to apply to the torch values beyond the kth value
  mask = logits < kth_value
  output = torch.where(mask,-torch.inf,logits)
  return output
  print(output)

# Calling the function on the fake logits
top_k_filter(fake_logits,5)

# Version 2, using sort and scatter. So, returning exactly the top k
def top_k_filter_sort(logits,k):
  # Using the clamp again
  k = min(k,logits.shape[-1])

  # Sorting the logits. Extracting the sorted indices and values
  sorted_values,sorted_indices = torch.sort(logits,descending=True,dim=-1)

  # Keeping only the kth sorted indices and values
  kth_sorted_indices = sorted_indices[:,:k]
  kth_sorted_values = sorted_values[:,:k]

  # Making an output tensor of the same shape as the logits tensor, filled with -inf
  output = torch.full_like(logits,-torch.inf)

  rows = torch.arange(sorted_values.shape[0])[:,None]

  output[rows,kth_sorted_indices] = kth_sorted_values

  return output
  # Using scatter to update the output tensor with the top k values
top_k_filter_sort(fake_logits,2)

# Version 3 using what will likely be allowed in interviews
def top_k_interv(logits,k):

  # Clamp
  k = min(k,logits.shape[-1])

  # if the k value is <= 0 turn off the filter
  if k <=0:
    k = logits.shape[-1]

  # getting the topk logits and indices
  topk_logits,topk_indices = torch.topk(logits,k,dim=-1)

  # Making an output tensor, because this is precise topk, where exactly
  # k elements are returned, so we're going by the indices, not value comparisons
  output = torch.full_like(logits,-torch.inf)

  # Using the scatter method this time instead of manual indexing
  output.scatter_(-1,topk_indices,topk_logits)
  print(output)
  return output

top_k_interv(fake_logits,1)

