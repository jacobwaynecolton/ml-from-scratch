import torch
torch.manual_seed(0)
V = 6
table = torch.randn(V, V).log_softmax(dim=-1)        # table[prev] = log-probs of the next token
seqs = torch.tensor([[0, 3, 1],
                     [0, 2, 5],
                     [0, 4, 4]])                       # 3 beams, each 3 tokens long
scores = torch.tensor([-1.0, -2.0, -0.5])             # one running score per beam
state = torch.arange(6).reshape(3, 2)   # one row per beam: beam 0 → [0, 1], beam 1 → [2, 3], beam 2 → [4, 5]


def next_logprobs_batched(table,seqs) :
  # Returning the batched log probabilities for the next token prediction
  return table[seqs[:,-1]]

def select_top(scores,next_lp,k):
  # Returns (vals, parent, tok)

  # First adding the parent values
  next_lp_with_parent = next_lp + scores[:,None]


  # Flatenning the list and extracting the top k
  topk_vals, topk_indices = torch.topk(next_lp_with_parent.flatten(),k,-1)

  # From these flattened indices we can calculate the row (parent)
  # and the column (tok)

  parents = topk_indices // next_lp.shape[-1]
  toks = topk_indices % next_lp.shape[-1]

  return (topk_vals,parents,toks)


def extend(seqs,parent,tok):
  # Return (k,T+1)
  # first copying the winners parent rows to make the new base seqs
  new_seqs = seqs[parent]

  # Then appending the new token on to these seqs using cat
  new_seqs = torch.cat((new_seqs,tok[:,None]),dim=-1)

  return new_seqs


def safe_topk(x,k):
  # Implementing topk with a clamp
  k = min(k,len(x))

  return torch.topk(x,k)


def reorder_state(state,parent):
  # Reordering the KV cache/state after the sequences have been updated

  return state[parent]


if __name__ == "__main__":
  vals, parents, toks = select_top(scores, next_logprobs_batched(table, seqs), 3)
  new_seqs = extend(seqs, parents, toks)

  # Check select_top against a brute-force scan of every (beam, token) pair
  all_pairs = sorted(((scores[b] + table[seqs[b, -1], t]).item(), b, t)
                     for b in range(3) for t in range(V))[::-1][:3]
  assert torch.allclose(vals, torch.tensor([p[0] for p in all_pairs]))
  assert parents.tolist() == [p[1] for p in all_pairs]
  assert toks.tolist() == [p[2] for p in all_pairs]

  # Each new beam is its parent's row with the chosen token appended
  assert new_seqs.shape == (3, 4)
  for i in range(3):
    assert new_seqs[i, :-1].tolist() == seqs[parents[i]].tolist()
    assert new_seqs[i, -1] == toks[i]

  # Asking for more than exists gets clamped instead of crashing
  assert len(safe_topk(torch.randn(4), 10).values) == 4

  # Cache rows follow their beams
  assert torch.equal(reorder_state(state, parents), state[parents])

  print("new beams:\n", new_seqs)
  print("scores:", vals)
  print("reordered state:\n", reorder_state(state, parents))
  print("all checks pass")