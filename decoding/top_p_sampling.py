import torch
import torch.nn.functional as F

torch.manual_seed(12)
# Making example data
logits = torch.randn(2,3)
p = 0.6
def top_p_filter(logits,p):
  # logits: (B,V)

  # Calculating the probabilities
  probs = F.softmax(logits,-1)
  # Sorting the probabilities
  sorted_probs,sorted_indices = torch.sort(probs,-1,descending=True)
  cumsum = torch.cumsum(sorted_probs,-1)
  mask = cumsum - sorted_probs < p

  # Zeroing out the tokens which were > p
  out = torch.where(mask,sorted_probs,0)
  # Getting the sum for each sample
  sample_sum = out.sum(-1,keepdim=True)

  # Renormalizing the distribution
  out /= sample_sum

  # Sampling from the renormalized distribution
  out_tok = out.multinomial(1)

  # Map that index back against the original ordering


  # You can't use sorted indices like this and you must use torch.gather instead
  # it's a good lesson for when to use gather

  return sorted_indices.gather(-1,out_tok)




top_p_filter(logits,p)