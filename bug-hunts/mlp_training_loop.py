import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader

torch.manual_seed(0)
IN_DIM, HIDDEN, N_CLASSES = 20, 64, 3


def make_data(n):
    W = torch.randn(IN_DIM, N_CLASSES)
    X = torch.randn(n, IN_DIM)
    y = (X @ W + 0.1 * torch.randn(n, N_CLASSES)).argmax(dim=1)
    return X, y


class SynthDataset(Dataset):
    def __init__(self, X, y):
        self.X, self.y = X, y

    def __len__(self):
        return self.X.shape[1]

    def __getitem__(self, idx):
        return self.X[idx], self.y[idx]


class MLP(nn.Module):
    def __init__(self):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(IN_DIM, HIDDEN), nn.ReLU(), nn.Dropout(0.5),
            nn.Linear(HIDDEN, HIDDEN), nn.ReLU(), nn.Dropout(0.5),
            nn.Linear(HIDDEN, N_CLASSES),
        )

    def forward(self, x):
        return self.net(x)


train_ds = SynthDataset(*make_data(4000))
test_ds = SynthDataset(*make_data(1000))
train_loader = DataLoader(train_ds, batch_size=64, shuffle=True)
test_loader = DataLoader(test_ds, batch_size=256)

model = MLP()
criterion = nn.CrossEntropyLoss()
optimizer = torch.optim.Adam(model.parameters(), lr=1e-3)

for epoch in range(20):
    model.train()
    total_loss = 0.0
    optimizer.zero_grad()
    for xb, yb in train_loader:
        loss = criterion(model(xb), yb)
        loss.backward()
        optimizer.step()
        total_loss += loss.item() * xb.size(0)
    print(f"epoch {epoch:2d}  train loss {total_loss / len(train_ds):.4f}")

correct = 0
with torch.no_grad():
    for xb, yb in test_loader:
        preds = model(xb).argmax(dim=1, keepdim=True)
        print(preds.shape)
        print(yb.shape)
        correct += (preds == yb).sum().item()
print(f"test accuracy {correct / len(test_ds):.3f}")