import math
import torch
import torch.nn as nn
import torch.nn.functional as F


class MaskedMultiHeadAttention(nn.Module):
    def __init__(self, d_model, n_heads, dropout=0.0):
        super().__init__()
        assert d_model % n_heads == 0
        self.d_model = d_model
        self.n_heads = n_heads
        self.d_head = d_model // n_heads
        self.qkv = nn.Linear(d_model, 3 * d_model)
        self.out_proj = nn.Linear(d_model, d_model)
        self.dropout = nn.Dropout(dropout)

    def _split_heads(self, x):
        # (B, T, D) -> (B, H, T, d_head)
        B, T, _ = x.shape
        return x.view(B, T, self.n_heads, self.d_head).transpose(1, 2)

    def forward(self, x, key_padding_mask=None, causal=True):
        """
        x:                (B, T, D)
        key_padding_mask: (B, T) bool, True where the token is padding
        returns:          output (B, T, D), attention weights (B, H, T, T)
        """
        B, T, D = x.shape
        q, k, v = self.qkv(x).chunk(3, dim=-1)
        q, k, v = self._split_heads(q), self._split_heads(k), self._split_heads(v)

        scores = q @ k.transpose(-2, -1)  # (B, H, T, T)

        if causal:
            allowed = torch.tril(torch.ones(T, T, dtype=torch.bool, device=x.device))
            scores = scores.masked_fill(allowed, float("-inf"))

        if key_padding_mask is not None:
            pad = key_padding_mask[:, None, :, None]
            scores = scores.masked_fill(pad, float("-inf"))

        attn = F.softmax(scores, dim=-2)
        attn = self.dropout(attn)
        out = attn @ v  # (B, H, T, d_head)

        out = out.reshape(B, T, D)
        return self.out_proj(out), attn


