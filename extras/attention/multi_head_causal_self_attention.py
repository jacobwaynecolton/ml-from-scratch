import torch.nn as nn
import torch
import math

class MultiHeadAttention(nn.Module):
  def __init__(self,d_model,n_heads):
     super().__init__()
     # Including checks in the initialization
     assert d_model % n_heads == 0

     self.H = n_heads
     self.C = d_model
     self.Wq = nn.Linear(d_model,d_model)
     self.Wk = nn.Linear(d_model,d_model)
     self.Wv = nn.Linear(d_model,d_model)
     self.Wo = nn.Linear(d_model,d_model)
     self.d_h = self.C//self.H

  def forward(self,X):
    # X: (B,T,C)
    B, T, C = X.shape
    # Compute the Q, K, V matrices by passing X through the
    # Wq Wk and Wv matrices
    Q = self.Wq(X)
    K = self.Wk(X)
    V = self.Wv(X)

    # Split up Q K & V according to the head count
    # Swapping the order of tokens and heads as well
    Q_split = Q.view(B,T,self.H,self.d_h).transpose(1,2)
    K_split = K.view(B,T,self.H,self.d_h).transpose(1,2)
    V_split = V.view(B,T,self.H,self.d_h).transpose(1,2)

    # Calculating the Query Key dot products
    # Then scaling by sqrt(d_h)
    qk_pairs = (Q_split @ K_split.transpose(-2,-1)) / math.sqrt(self.d_h)

    # Next we create the mask using torch.triu() for the upper triangle
    mask = torch.triu(torch.ones_like(qk_pairs),diagonal= 1).bool()

    # Applying the upper triangle mask (not including the main diagonal)
    qk_pairs = torch.masked_fill(qk_pairs,mask,-torch.inf)

    # Applying the softmax function to the qk_pairs
    qk_probs = torch.softmax(qk_pairs,-1)

    # Calculating the weighted avg using the softmax probabilities and the values
    # from the value matrix
    out = qk_probs @ V_split

    # Now out : (B,H,T,b_h), but we must return (B,T,C)
    # So we reswap H and T using torch.transpose, then using reshape,
    # bring it to its original input shape
    out = out.transpose(1,2).reshape(B,T,C)

    # Then we @ with the output matrix to blend the output of the individual heads
    out = self.Wo(out)

    # Returning the updated word embeddings
    return out


if __name__ == "__main__":
    torch.manual_seed(0)
    B, T, C, H = 2, 6, 16, 4
    x = torch.randn(B, T, C)
    mha = MultiHeadAttention(C, H)
    out = mha(x)
    assert out.shape == (B, T, C), f"shape: expected {(B, T, C)}, got {tuple(out.shape)}"
    print("PASS shape")

    x2 = x.clone(); x2[:, 4:] = torch.randn(B, T - 4, C)
    assert torch.allclose(mha(x2)[:, :4], out[:, :4], atol=1e-6), "causal: changing positions 4+ changed the output at positions 0-3"
    print("PASS causal")

    n = sum(p.numel() for p in mha.parameters())
    assert n == 4 * C * C + 4 * C, f"parameters: expected {4 * C * C + 4 * C}, got {n}"
    print("PASS parameter count")

    ref = nn.MultiheadAttention(C, H, batch_first=True)
    with torch.no_grad():
        ref.in_proj_weight.copy_(torch.cat([mha.Wq.weight, mha.Wk.weight, mha.Wv.weight]))
        ref.in_proj_bias.copy_(torch.cat([mha.Wq.bias, mha.Wk.bias, mha.Wv.bias]))
        ref.out_proj.weight.copy_(mha.Wo.weight)
        ref.out_proj.bias.copy_(mha.Wo.bias)
    blocked = torch.ones(T, T, dtype=torch.bool).triu(1)
    expected, _ = ref(x, x, x, attn_mask=blocked, need_weights=False)
    assert torch.allclose(out, expected, atol=1e-5), f"vs nn.MultiheadAttention: max difference {(out - expected).abs().max().item():.2e}"
    print("PASS matches nn.MultiheadAttention with the same weights")

    failed = False
    try:
        MultiHeadAttention(10, 4)
    except Exception:
        failed = True
    assert failed, "MultiHeadAttention(10, 4) should raise: 10 isn't divisible by 4"
    print("PASS rejects d_model not divisible by n_heads")
    print("all tests passed")
