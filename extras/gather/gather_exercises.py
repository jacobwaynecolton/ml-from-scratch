def last_hidden(x,lengths):
  # x : (B, T, D), one D-dim vector at every position in the sentence
  # lengths : ( B,), how many real tokens each sentence has
  # returns : (B,D), the vector at each sentence's last real position

  # for each sentence in the batch, take the vector at the position lengths[b] - 1

  idx = lengths - 1
  idx = idx[:,None,None].expand(len(lengths),1,x.shape[-1])

  return x.gather(1,idx).squeeze(dim=1)



