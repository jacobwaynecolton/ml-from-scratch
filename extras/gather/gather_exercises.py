def reorder(x):
  # Creating the indices from the input tensor in descending order
  idx = x.argsort(dim = -1, descending = True)

  # Using gather to update the order of x
  x_sorted = x.gather(-1,idx)
  return x_sorted, idx

reorder(x)

def unreorder(x_sorted,idx):
  # Undoing the reordering from reorder(x). Using the same idx but with scatter
  # rather than gather and x_sorted as the source tensor
  x_unsorted = x_sorted.scatter(-1,idx,x_sorted)
  return x_unsorted


unreorder(*reorder(x))

def target_logprobs(logits,targets):
  # Taking in logits : (B,V) and targets: (B,) which is the correct token id
  # for each row.
  # Return: (B,), the log probability the model gave the correct token

  # Applying log_softmax to the logits
  log_probs = torch.log_softmax(logits,dim=-1)

  # Using gather to pick out the targets in each row
  target_probs = log_probs.gather(-1,targets[:,None])

  return target_probs

