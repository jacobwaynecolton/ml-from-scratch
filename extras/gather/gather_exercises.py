def seq_mean_logprob(logits,targets,mask):
  # logits (B, T, V), targets: (B, T), mask: (B, T), 1 = real token, 0 = padding
  # returns: a single number (scalar), the average log-prob over real tokens only

  # applying log_softmax over the V dimension
  log_probs = F.log_softmax(logits,-1)

  # Get the correct token in each tensor using gather
  correct_tok = log_probs.gather(-1,targets[...,None])

  # taking only the non-padding tokens for calculating the mean
  non_padding_correct = correct_tok[mask == 1]

  # Returning the mean
  return non_padding_correct.mean()

