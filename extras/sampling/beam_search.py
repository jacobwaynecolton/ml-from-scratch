import torch

torch.manual_seed(0)
V = 5
table = torch.randn(V, V).log_softmax(dim=-1)   # table[prev] = log-probs of the next token

# Single sequence: seq is a list or 1D tensor of token ids -> returns (V,)
# Use for greedy and brute force.
def next_logprobs(seq):
    return table[seq[-1]]

# Batched: beams is a (k, T) LongTensor, one beam per ROW -> returns (k, V)
# Use inside beam search.
def next_logprobs_batched(beams):
    return table[beams[:, -1]]


def beam_search(next_logprobs_batched, start: int, beam_width: int, max_new: int):
    """Returns (best_seq: list[int], best_score: float).
    best_seq includes start; best_score sums log-probs of the new tokens only."""
    beams = torch.tensor([[start]])   # (1, 1)
    scores = torch.tensor([0.0])      # (1,)
    for _ in range(max_new):
        # TODO: lp = next_logprobs_batched(beams) -> (k, V)
        lp = next_logprobs_batched(beams)
        # TODO: add scores, flatten, topk, recover parent (// V) and token (% V)
        totals = scores[:,None] + lp
        flat_totals = totals.view(-1)
        # alternatively, i could have used totals.flatten()

        topk_vals, topk_indices = flat_totals.topk(min(beam_width,flat_totals.numel()))
        parents = topk_indices // totals.shape[-1]
        tokens = topk_indices % totals.shape[-1]


        # TODO: beams = cat(beams[parent], new tokens as a column); scores = top scores
        beams = torch.cat((beams[parents],tokens[:,None]),dim=1)
        scores = topk_vals
    # TODO: pick the best beam
    best_index = torch.argmax(scores)
    best_seq = beams[best_index]
    best_score = scores[best_index]
    return best_seq.tolist(), best_score.item()


def greedy(next_logprobs, start: int, max_new: int):
    """Returns (seq: list[int], score: float). About 5 lines, uses next_logprobs."""

    seq = torch.tensor([start])
    score = torch.tensor([0.])

    # Iterating for the amount of max_new tokens
    for _ in range(max_new):
      # Getting the logprobs for the current sequence's final token
      lp = next_logprobs(seq)

      # getting the tok
      tok = torch.argmax(lp)[None]

      # concatenating the tok onto the sequence
      seq = torch.cat((seq,tok))

      # Adding the lp to the score for the chosen tok
      score += lp[tok]

    return seq.tolist(), score.item()


# Tests: run for every possible start token, not just 0
for s in range(V):
    g_seq, g_score = greedy(next_logprobs, s, 4)
    b_seq, b_score = beam_search(next_logprobs_batched, s, 1, 4)
    assert b_seq == g_seq and abs(b_score - g_score) < 1e-6, f"greedy mismatch, start={s}"


